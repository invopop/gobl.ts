#!/usr/bin/env node
// Vendors GOBL's own built example envelopes as test fixtures, and generates
// the type-level test that checks them against the generated types.
//
// These documents are GOBL's real output across every supported country and
// addon, so compiling them against our types is the strongest correctness
// signal available: if a generated interface is missing a property GOBL emits,
// or narrows an enum too far, `tsc` says so.
//
// Run when bumping GOBL:  node scripts/vendor-fixtures.mjs [path-to-gobl]
import { readFileSync, writeFileSync, readdirSync, rmSync, mkdirSync } from 'node:fs';
import { join, relative } from 'node:path';

const goblRoot = process.argv[2] ?? '../gobl';
const examplesDir = join(goblRoot, 'examples');
const fixturesDir = 'test/fixtures';

/** Recursively collects every built envelope under an `out/` directory. */
function findEnvelopes(dir) {
  const found = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...findEnvelopes(path));
    else if (entry.name.endsWith('.json') && dir.endsWith('/out')) found.push(path);
  }
  return found;
}

// The document `$schema` selects which generated type a fixture is checked
// against. Anything not listed here is skipped rather than silently untested.
const TYPES = {
  'https://gobl.org/draft-0/bill/invoice': 'bill.Invoice',
  'https://gobl.org/draft-0/bill/order': 'bill.Order',
  'https://gobl.org/draft-0/bill/delivery': 'bill.Delivery',
  'https://gobl.org/draft-0/bill/payment': 'bill.Payment',
  'https://gobl.org/draft-0/bill/status': 'bill.Status',
  'https://gobl.org/draft-0/org/party': 'org.Party',
  'https://gobl.org/draft-0/tax/identity': 'tax.Identity',
};

rmSync(fixturesDir, { recursive: true, force: true });
mkdirSync(fixturesDir, { recursive: true });

const cases = [];
const skipped = [];

for (const path of findEnvelopes(examplesDir).sort()) {
  const raw = readFileSync(path, 'utf8');
  const env = JSON.parse(raw);
  const schema = env?.doc?.$schema;
  const type = TYPES[schema];
  if (!type) {
    skipped.push(`${relative(examplesDir, path)} (${schema})`);
    continue;
  }
  const name = relative(examplesDir, path)
    .replace(/\/out\//, '/')
    .replace(/\//g, '-');
  writeFileSync(join(fixturesDir, name), JSON.stringify(env, null, 2) + '\n');
  cases.push({ name, source: relative(examplesDir, path), type, env });
}

const modules = [...new Set(cases.map((c) => c.type.split('.')[0]))].sort();

let out = `// Code generated by scripts/vendor-fixtures.mjs. DO NOT EDIT.
//
// Every document below is real output from GOBL's own example suite. Checking
// them with \`satisfies\` asserts two things at once: that our generated types
// accept everything GOBL produces, and — through excess property checking —
// that they do not omit any property GOBL emits.

import type { Envelope } from '../src/helpers.js';
${modules.map((m) => `import type * as ${m} from '../src/gen/${m}/index.js';`).join('\n')}

`;

for (const c of cases) {
  out += `// ${c.source}\n({\n${JSON.stringify(c.env, null, 2).slice(2, -2)}\n}) satisfies Envelope<${c.type}>;\n\n`;
}

writeFileSync('test/fixtures.test-d.ts', out);

console.log(`vendored ${cases.length} fixtures covering ${modules.length} modules`);
for (const s of skipped) console.log(`  skipped ${s}`);
